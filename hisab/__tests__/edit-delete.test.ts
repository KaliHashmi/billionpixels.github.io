import { canDeleteDocuments, canEdit, canEditDocuments } from '../src/domain/auth';
import {
  clearCheque,
  deleteMove,
  deletePayment,
  editPayment,
  invoiceStatus,
  newInvoiceLine,
  newMove,
  PaymentInput,
  postMove,
  reconcileStatementLine,
  registerPayment,
  resetToDraft,
  reverseMove,
  saveDraft,
  saveStatementLine,
} from '../src/domain/engine';
import { unallocated } from '../src/domain/management';
import { deletePayrollRun, newPayrollRun, payPayroll, postPayroll, savePayrollRun } from '../src/domain/operations';
import { postTaxClosing, trialBalance } from '../src/domain/reports';
import { createCompany } from '../src/domain/template';
import { AppState, Employee, Partner } from '../src/domain/types';
import { newId } from '../src/domain/utils';

const D = '2026-03-10';

function books() {
  let s = createCompany({ companyName: 'Muscat Co', currency: 'OMR', vatRate: 5, country: 'OM' });
  const customer: Partner = { id: newId(), name: 'Customer', email: '', phone: '', street: '', city: '', country: '', taxId: '', isCustomer: true, isVendor: false, notes: '', active: true };
  s = { ...s, partners: [customer] };
  return { s, customer, bank: s.journals.find((j) => j.type === 'bank')! };
}

function invoice(s: AppState, partnerId: string, price: number) {
  let mv = newMove(s, 'out_invoice', { partnerId, date: D, invoiceDate: D });
  mv = { ...mv, invoiceLines: [newInvoiceLine({ label: 'Item', quantity: 1, priceUnit: price, taxIds: [s.settings.defaultSaleTaxId!] })] };
  return { s: postMove(saveDraft(s, mv), mv.id), id: mv.id };
}

const receipt = (partnerId: string, journalId: string, amount: number, moveIds?: string[]): PaymentInput => ({
  paymentType: 'inbound',
  partnerType: 'customer',
  partnerId,
  amount,
  date: D,
  journalId,
  memo: 'r',
  method: 'bank_transfer',
  moveIds,
});

const balanced = (s: AppState) => {
  const tb = trialBalance(s, '2026-01-01', '2026-12-31').totals;
  expect(tb.debit).toBeCloseTo(tb.credit, 6);
};
const move = (s: AppState, id: string) => s.moves.find((m) => m.id === id)!;

describe('roles on issued documents', () => {
  it('lets administrators edit and delete, accountants only delete, viewers neither', () => {
    expect([canEditDocuments('admin'), canDeleteDocuments('admin'), canEdit('admin')]).toEqual([true, true, true]);
    expect([canEditDocuments('accountant'), canDeleteDocuments('accountant'), canEdit('accountant')]).toEqual([false, true, true]);
    expect([canEditDocuments('viewer'), canDeleteDocuments('viewer'), canEdit('viewer')]).toEqual([false, false, false]);
  });
});

describe('deleting invoices and entries', () => {
  it('removes a paid invoice and leaves its payment as an unallocated receipt', () => {
    const { s: s0, customer, bank } = books();
    let { s, id } = invoice(s0, customer.id, 100);
    const pay = registerPayment(s, receipt(customer.id, bank.id, 105, [id]));
    s = deleteMove(pay.state, id);
    expect(s.moves.some((m) => m.id === id)).toBe(false);
    expect(s.reconciles).toHaveLength(0);
    expect(unallocated(s).map((u) => [u.kind, u.amount])).toEqual([['receipt', 105]]);
    balanced(s);
  });

  it('deletes drafts and numbered drafts, but not entries generated by a payment', () => {
    const { s: s0, customer, bank } = books();
    let { s, id } = invoice(s0, customer.id, 100);
    s = resetToDraft(s, id);
    expect(move(s, id).name).toMatch(/INV/);
    s = deleteMove(s, id);
    expect(s.moves).toHaveLength(0);
    const pay = registerPayment(s, receipt(customer.id, bank.id, 5));
    expect(() => deleteMove(pay.state, pay.payment.moveId)).toThrow(/payment voucher/);
  });

  it('asks to delete the credit note first', () => {
    const { s: s0, customer } = books();
    const inv = invoice(s0, customer.id, 100);
    const credit = reverseMove(inv.s, inv.id, { date: D, reason: 'x', post: true });
    expect(() => deleteMove(credit.state, inv.id)).toThrow(/credit note/);
    const s = deleteMove(deleteMove(credit.state, credit.move.id), inv.id);
    expect(s.moves).toHaveLength(0);
    balanced(s);
  });

  it('respects the lock date for posted documents', () => {
    const { s: s0, customer } = books();
    const { s, id } = invoice(s0, customer.id, 100);
    const locked = { ...s, settings: { ...s.settings, lockDate: '2026-03-31' } };
    expect(() => deleteMove(locked, id)).toThrow(/lock date/);
  });

  it('deleting a VAT closing reopens the period, and it can be closed again', () => {
    const { s: s0, customer } = books();
    let s = invoice(s0, customer.id, 100).s;
    s = postTaxClosing(s, '2026-01-01', '2026-03-31');
    expect(s.settings.taxLockDate).toBe('2026-03-31');
    const closing = s.moves.find((m) => m.origin === 'tax_closing')!;
    s = deleteMove(s, closing.id);
    expect(s.settings.taxLockDate).toBeUndefined();
    s = postTaxClosing(invoice(s, customer.id, 50).s, '2026-01-01', '2026-03-31');
    expect(s.moves.find((m) => m.origin === 'tax_closing')!.lines.find((l) => l.label === 'VAT payable')!.credit).toBe(7.5);
    balanced(s);
  });
});

describe('editing an issued invoice', () => {
  it('keeps the number and matches its payment again after re-posting', () => {
    const { s: s0, customer, bank } = books();
    let { s, id } = invoice(s0, customer.id, 100);
    const name = move(s, id).name;
    s = registerPayment(s, receipt(customer.id, bank.id, 105, [id])).state;
    s = resetToDraft(s, id);
    expect(invoiceStatus(s, move(s, id)).paymentState).not.toBe('paid');
    const edited = { ...move(s, id), invoiceLines: move(s, id).invoiceLines.map((l) => ({ ...l, priceUnit: 120 })) };
    s = postMove(saveDraft(s, edited), id);
    expect(move(s, id).name).toBe(name);
    expect(move(s, id).rematchLineIds).toBeUndefined();
    const st = invoiceStatus(s, move(s, id));
    expect(st.total).toBe(126);
    expect(st.residual).toBe(21);
    balanced(s);
  });
});

describe('vouchers', () => {
  it('deleting a receipt makes the invoice due again', () => {
    const { s: s0, customer, bank } = books();
    const inv = invoice(s0, customer.id, 100);
    const pay = registerPayment(inv.s, receipt(customer.id, bank.id, 105, [inv.id]));
    const s = deletePayment(pay.state, pay.payment.id);
    expect(s.payments).toHaveLength(0);
    expect(invoiceStatus(s, move(s, inv.id)).residual).toBe(105);
    balanced(s);
  });

  it('deleting a cleared cheque also removes its clearance', () => {
    const { s: s0, customer, bank } = books();
    const inv = invoice(s0, customer.id, 100);
    const pay = registerPayment(inv.s, { ...receipt(customer.id, bank.id, 105, [inv.id]), method: 'cheque', chequeNumber: '77' });
    let s = clearCheque(pay.state, pay.payment.id, '2026-03-12');
    s = deletePayment(s, pay.payment.id);
    expect(s.moves.filter((m) => m.origin === 'cheque' || m.origin === 'payment')).toHaveLength(0);
    balanced(s);
  });

  it('refuses to delete or edit a payment matched on a bank statement', () => {
    const { s: s0, customer, bank } = books();
    const pay = registerPayment(s0, receipt(customer.id, bank.id, 50));
    let s = saveStatementLine(pay.state, { id: 'sl', journalId: bank.id, date: D, label: 'in', amount: 50, ref: '', reconciled: false });
    const liquidity = move(s, pay.payment.moveId).lines.find((l) => l.kind === 'other')!;
    s = reconcileStatementLine(s, 'sl', [liquidity.id]);
    expect(() => deletePayment(s, pay.payment.id)).toThrow(/bank reconciliation/);
    expect(() => editPayment(s, pay.payment.id, receipt(customer.id, bank.id, 60))).toThrow(/bank reconciliation/);
  });

  it('editing keeps the voucher number and the invoices it paid', () => {
    const { s: s0, customer, bank } = books();
    const inv = invoice(s0, customer.id, 100);
    const pay = registerPayment(inv.s, receipt(customer.id, bank.id, 105, [inv.id]));
    const res = editPayment(pay.state, pay.payment.id, { ...receipt(customer.id, bank.id, 60), date: '2026-03-15', memo: 'corrected' });
    expect(res.payment).toMatchObject({ id: pay.payment.id, name: pay.payment.name, moveId: pay.payment.moveId, amount: 60, memo: 'corrected' });
    expect(res.state.payments).toHaveLength(1);
    expect(invoiceStatus(res.state, move(res.state, inv.id)).residual).toBe(45);
    expect(() => editPayment(res.state, pay.payment.id, { ...receipt(customer.id, bank.id, 60), paymentType: 'outbound' })).toThrow(/receipt cannot/);
    balanced(res.state);
  });
});

describe('payroll', () => {
  it('deletes a paid payroll with its journal entries', () => {
    let { s } = books();
    const e: Employee = { id: newId(), name: 'A', code: '', position: '', nationality: 'omani', basicSalary: 500, housingAllowance: 100, transportAllowance: 0, otherAllowance: 0, socialInsurance: true, bankName: '', iban: '', joinDate: D, active: true };
    s = { ...s, employees: [e] };
    const run = newPayrollRun(s, '2026-03');
    s = payPayroll(postPayroll(savePayrollRun(s, run), run.id), run.id, s.journals.find((j) => j.type === 'bank')!.id, '2026-03-28');
    expect(s.payrollRuns[0].issued).toBe(true);
    s = deletePayrollRun(s, run.id);
    expect(s.payrollRuns).toHaveLength(0);
    expect(s.moves.filter((m) => m.origin === 'payroll')).toHaveLength(0);
  });
});
